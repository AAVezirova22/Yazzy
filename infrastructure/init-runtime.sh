#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$PG_APP_PASSWORD" <<'SQL'
CREATE ROLE yazzy_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT USAGE ON SCHEMA public TO yazzy_app;
ALTER DEFAULT PRIVILEGES FOR ROLE yazzy_admin IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO yazzy_app;
ALTER DEFAULT PRIVILEGES FOR ROLE yazzy_admin IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO yazzy_app;
SQL
